"""Build the MAESTRO distribution and generated documentation.

    python tools/build.py           # write maestro-merged.ttl, the catalog, docs/terms.md and dist/
    python tools/build.py --check   # report stale generated files, write nothing

Outputs (the first three are committed; dist/ is gitignored and rewritten from scratch):
  maestro-merged.ttl                                  merged single-file ontology
  catalog-v001.xml                                    root catalog with relative paths
  docs/terms.md                                       generated term dictionary
  dist/maestro-full.ttl / .owl / .jsonld              merged single-file ontology, three syntaxes
  dist/<layer>/<module>.ttl + dist/catalog-v001.xml   module copies for offline loading

Before writing, every module must carry the umbrella's owl:versionInfo, a
versionIRI of <module IRI>/<version> and dct:isPartOf the umbrella; the
build fails on drift rather than restamping silently.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import warnings
from pathlib import Path

from rdflib import Graph, Literal, URIRef
from rdflib.compare import isomorphic
from rdflib.namespace import OWL, RDF, RDFS, SKOS, DCTERMS

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402
from common import (MH_NS, ONTOLOGY_IRI, MODULES, PKG, layer_dir, module_path,  # noqa: E402
                    module_iri, parse, ontology_of, rel, new_graph, write_text, read_text)
from serialize import serialize  # noqa: E402

DIST = PKG / "dist"                 # disposable: removed and rewritten by every build
MERGED_TTL = common.MERGED_FILE
TERMS_MD = PKG / "docs" / "terms.md"
ROOT_CATALOG = PKG / "catalog-v001.xml"
MAPPING_PREDICATES = [SKOS.exactMatch, SKOS.closeMatch, SKOS.broadMatch, SKOS.narrowMatch, SKOS.relatedMatch,
                      RDFS.subClassOf, RDFS.subPropertyOf]


def banner(title: str, iri: str, version: str) -> str:
    return (f"# {title}\n# {iri}  (version {version})\n"
            f"# Part of MAESTRO. License: MIT. Generated by tools/build.py - do not edit.\n")


def load_all() -> tuple[dict[Path, Graph], Graph, str, list[str]]:
    """Parse umbrella and modules; return graphs, the version and any drift problems."""
    problems: list[str] = []
    umbrella = parse(common.UMBRELLA_FILE)
    version = str(next(umbrella.objects(ONTOLOGY_IRI, OWL.versionInfo), ""))
    if not version:
        problems.append("umbrella has no owl:versionInfo")
    graphs: dict[Path, Graph] = {common.UMBRELLA_FILE: umbrella}
    for layer, stem in MODULES:
        path = module_path(layer, stem)
        g = parse(path)
        graphs[path] = g
        iri = ontology_of(g)
        if iri != module_iri(stem):
            problems.append(f"{rel(path)}: ontology IRI {iri} != {module_iri(stem)}")
            continue
        v = str(next(g.objects(iri, OWL.versionInfo), ""))
        if v != version:
            problems.append(f"{rel(path)}: owl:versionInfo {v!r} != umbrella {version!r}")
        vi = next(g.objects(iri, OWL.versionIRI), None)
        if str(vi) != f"{iri}/{version}":
            problems.append(f"{rel(path)}: owl:versionIRI {vi} != {iri}/{version}")
        if (iri, DCTERMS.isPartOf, ONTOLOGY_IRI) not in g:
            problems.append(f"{rel(path)}: missing dct:isPartOf {ONTOLOGY_IRI}")
    return graphs, umbrella, version, problems


def merged_graph(graphs: dict[Path, Graph], umbrella: Graph) -> Graph:
    merged = new_graph()
    for g in graphs.values():
        for prefix, ns in g.namespaces():
            merged.bind(prefix, ns, override=False)
        merged += g
    for _, stem in MODULES:
        merged.remove((module_iri(stem), None, None))
    merged.remove((ONTOLOGY_IRI, OWL.imports, None))
    comment = str(next(umbrella.objects(ONTOLOGY_IRI, RDFS.comment), ""))
    merged.set((ONTOLOGY_IRI, RDFS.comment, Literal(
        comment + " This file is the merged form of all modules in one document.", lang="en")))
    return merged


# --------------------------------------------------------------------------- catalog and docs

def catalog_xml(entries: list[tuple[str, str]]) -> str:
    lines = ['<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
             '<catalog prefer="public" xmlns="urn:oasis:names:tc:entity:xmlns:xml:catalog">']
    for iri, uri in sorted(entries):
        lines.append(f'    <uri name="{iri}" uri="{uri}"/>')
    lines.append("</catalog>")
    return "\n".join(lines) + "\n"


def root_catalog_text() -> str:
    entries = [(str(ONTOLOGY_IRI), "maestro.ttl")]
    entries += [(str(module_iri(stem)), f"{layer_dir(layer)}/{stem}.ttl") for layer, stem in MODULES]
    return catalog_xml(entries)


def dist_catalog_text() -> str:
    entries = [(str(ONTOLOGY_IRI), "maestro-full.ttl")]
    entries += [(str(module_iri(stem)), f"{layer_dir(layer)}/{stem}.ttl") for layer, stem in MODULES]
    return catalog_xml(entries)


def merged_text(graphs: dict[Path, Graph], umbrella: Graph, version: str) -> str:
    """Text of the merged single-file ontology."""
    title = str(next(umbrella.objects(ONTOLOGY_IRI, DCTERMS.title)))
    return serialize(merged_graph(graphs, umbrella), ONTOLOGY_IRI,
                     banner(title + " (merged, all modules)", str(ONTOLOGY_IRI), version))


def text(g: Graph, s, p) -> str:
    vals = [str(o) for o in g.objects(s, p)]
    return " ".join(vals).replace("|", "\\|").replace("\n", " ")


def terms_md(graphs: dict[Path, Graph], version: str) -> str:
    kinds = [("Classes", OWL.Class), ("Object properties", OWL.ObjectProperty),
             ("Datatype properties", OWL.DatatypeProperty), ("Individuals", OWL.NamedIndividual)]
    out = [f"# MAESTRO term dictionary ({version})", "",
           "Generated by `tools/build.py`; do not edit. One table per module, in load order. "
           "The MAESTRO source column names the MAESTRO 1.0 term whose definition was reused "
           "(`dct:source`, same concept) or adapted (`dct:references`, close concept). "
           "The standards column lists documentary matches and logical bridges to pinned references.", ""]
    for layer, stem in MODULES:
        g = graphs[module_path(layer, stem)]
        iri = module_iri(stem)
        title = text(g, iri, DCTERMS.title)
        out += [f"## {title}", "", f"Module IRI `{iri}`, file `{layer_dir(layer)}/{stem}.ttl`.", "",
                text(g, iri, DCTERMS.description), ""]
        for heading, typ in kinds:
            terms = sorted((s for s in g.subjects(RDF.type, typ) if isinstance(s, URIRef) and str(s).startswith(MH_NS)), key=str)
            if not terms:
                continue
            out += [f"### {heading}", "", "| Term | Label | Definition | MAESTRO source | Standards |", "|---|---|---|---|---|"]
            for t in terms:
                local = "maestro:" + str(t)[len(MH_NS):]
                label = text(g, t, RDFS.label)
                definition = text(g, t, SKOS.definition) or text(g, t, RDFS.comment)
                src = ", ".join(f"`{str(o).replace('https://w3id.org/maestro/', '')}`" for o in g.objects(t, DCTERMS.source))
                ref = ", ".join(f"~`{str(o).replace('https://w3id.org/maestro/', '')}`" for o in g.objects(t, DCTERMS.references))
                source = ", ".join(x for x in (src, ref) if x)
                stds = []
                for p in MAPPING_PREDICATES:
                    for o in g.objects(t, p):
                        if isinstance(o, URIRef) and not str(o).startswith(MH_NS):
                            stds.append(f"{p.n3(g.namespace_manager)} {o.n3(g.namespace_manager)}")
                out.append(f"| `{local}` | {label} | {definition} | {source} | {'; '.join(stds)} |")
            out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------- check / write

def generated_files() -> dict[Path, str]:
    """The committed generated files and the text each must have."""
    graphs, umbrella, version, problems = load_all()
    if problems:
        raise RuntimeError("; ".join(problems))
    return {MERGED_TTL: merged_text(graphs, umbrella, version), ROOT_CATALOG: root_catalog_text(),
            TERMS_MD: terms_md(graphs, version)}


def check() -> list[str]:
    """Problems with the committed generated files (empty when fresh)."""
    try:
        expected = generated_files()
    except RuntimeError as exc:
        return [str(exc)]
    problems = []
    for path, content in expected.items():
        if not path.exists():
            problems.append(f"{rel(path)} missing; run tools/build.py")
        elif read_text(path) != content:
            problems.append(f"{rel(path)} is stale; run tools/build.py")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        problems = check()
        for p in problems:
            print("STALE", p)
        print("generated files " + ("fresh" if not problems else "STALE"))
        return 1 if problems else 0

    graphs, umbrella, version, problems = load_all()
    if problems:
        print("\n".join(problems))
        print("version drift; nothing written")
        return 1

    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir(parents=True)
    for layer, stem in MODULES:
        src = module_path(layer, stem)
        dest = DIST / layer_dir(layer) / f"{stem}.ttl"
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
    write_text(DIST / "catalog-v001.xml", dist_catalog_text())

    merged = merged_graph(graphs, umbrella)
    text_ttl = merged_text(graphs, umbrella, version)
    write_text(DIST / "maestro-full.ttl", text_ttl)
    with warnings.catch_warnings():
        # rdflib's RDF/XML writer warns once per owl:AllDifferent / owl:AllDisjointClasses member
        # list; the lists are written correctly, as the round-trip check below confirms.
        warnings.filterwarnings("ignore", message="Assertions on .* other than RDF.first and RDF.rest are ignored")
        merged.serialize(DIST / "maestro-full.owl", format="pretty-xml", encoding="utf-8")
    merged.serialize(DIST / "maestro-full.jsonld", format="json-ld", encoding="utf-8", indent=2)
    for name in ("maestro-full.ttl", "maestro-full.owl", "maestro-full.jsonld"):
        if not isomorphic(Graph().parse(DIST / name), merged):  # round-trip check
            print(f"{rel(DIST / name)} does not read back as the merged graph")
            return 1

    # The committed files are written in place; nothing outside dist/ is ever removed.
    write_text(MERGED_TTL, text_ttl)
    if not isomorphic(Graph().parse(MERGED_TTL), merged):
        print(f"{rel(MERGED_TTL)} does not read back as the merged graph")
        return 1
    write_text(ROOT_CATALOG, root_catalog_text())
    write_text(TERMS_MD, terms_md(graphs, version))
    print(f"{len(MODULES)} modules, {len(merged)} triples merged -> {rel(MERGED_TTL)} and {rel(DIST)}/; "
          f"wrote {rel(ROOT_CATALOG)} and {rel(TERMS_MD)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
